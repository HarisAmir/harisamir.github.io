import assert from 'node:assert/strict'
import { mkdir, readFile, readdir } from 'node:fs/promises'
import { chromium } from 'playwright'
import { startServer } from './static-server.mjs'
import { pages } from '../.ssr/entry-server.js'

const { server, url } = await startServer()
let browser
try {
  browser = await chromium.launch({ executablePath: process.env.CHROME_EXECUTABLE || undefined })
  await mkdir('artifacts', { recursive: true })
  const context = await browser.newContext({ reducedMotion: 'reduce' })
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error' || message.text().includes('Hydration')) errors.push(message.text()) })
  const paths = pages.map(p => p.path)
  const links = new Set()

  for (const width of [1440, 768, 390, 320]) {
    await page.setViewportSize({ width, height: 1000 })
    for (const path of paths) {
      const response = await page.goto(url + path)
      assert.equal(response.status(), 200, path)
      await page.evaluate(() => document.fonts.ready)
      await page.evaluate(async () => { for (const img of document.images) { img.loading = 'eager'; await img.decode().catch(() => {}) } })
      assert.equal(await page.locator('h1').count(), 1, `${path}: one H1`)
      assert.equal(await page.title(), `${pages.find(p => p.path === path).title} — Haris Amir`)
      assert.equal(await page.locator('nav[aria-label="Main navigation"] a').count(), 4)
      assert.equal(await page.locator('nav[aria-label="Main navigation"] a[aria-current="page"]').count(), 1)
      assert(await page.locator('meta[name="description"]').getAttribute('content'))
      const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)
      assert(!overflow, `${path}: horizontal overflow at ${width}px`)
      const brokenImages = await page.locator('img').evaluateAll(images => images.filter(i => !i.hasAttribute('alt') || (i.complete && !i.naturalWidth)).map(i => i.src))
      assert.deepEqual(brokenImages, [], `${path}: image loading/alt text`)
      for (const href of await page.locator('a[href]').evaluateAll(a => a.map(el => el.getAttribute('href')))) links.add(href)
      if (['/', '/publications/', '/projects/'].includes(path) && [1440, 390].includes(width)) {
        // Scroll through the page before capture to load lazy project imagery.
        await page.evaluate(async () => { for (const img of document.images) { img.loading = 'eager'; await img.decode().catch(() => {}) } })
        await page.screenshot({ path: `artifacts/${path === "/" ? "home" : path.split('/')[1]}-${width}.png`, fullPage: true })
      }
    }
  }
  for (const href of links) {
    if (/^(https?:|mailto:|tel:)/.test(href)) continue
    const target = new URL(href, url)
    const response = await context.request.get(target.href)
    assert.equal(response.status(), 200, `Internal link: ${href}`)
    if (target.pathname.endsWith('.pdf')) {
      assert.match(response.headers()['content-type'] || '', /^application\/pdf\b/, `PDF content type: ${href}`)
      assert.equal((await response.body()).subarray(0, 5).toString(), '%PDF-', `PDF file, not an HTML fallback: ${href}`)
    }
    if (target.hash) assert((await response.text()).includes(`id="${target.hash.slice(1)}"`), `Anchor: ${href}`)
  }

  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(url + '/projects/')
  assert.equal(await page.locator('.project-card').count(), 4)
  const gallery = page.locator('#continual-event-detection .project-gallery')
  assert.equal(await gallery.locator('.gallery-slide').count(), 3)
  await gallery.getByRole('button', { name: 'Next figure' }).click()
  await gallery.locator('[aria-live="polite"]').filter({ hasText: '02 / 03' }).waitFor()
  await gallery.locator('.gallery-track').focus()
  await page.keyboard.press('ArrowRight')
  await gallery.locator('[aria-live="polite"]').filter({ hasText: '03 / 03' }).waitFor()
  assert(await gallery.getByRole('button', { name: 'Next figure' }).isDisabled())
  await gallery.getByRole('button', { name: 'Show figure 1' }).click()
  await gallery.locator('[aria-live="polite"]').filter({ hasText: '01 / 03' }).waitFor()
  assert.equal(await page.locator('#dls3d a[href$=".pdf"]').count(), 0, 'Unreleased manuscript has no PDF link')
  assert.equal(await page.locator('#dls3d .resource-forthcoming').count(), 2)
  const generatedFiles = await readdir('dist', { recursive: true })
  assert.deepEqual(generatedFiles.filter(file => file.endsWith('.pdf')).sort(), ['Haris_Amir_resume_vi.pdf', 'projects/continual-event-detection.pdf', 'projects/german-french-translation.pdf'], 'Only approved PDFs are published')
  const rangeResponse = await context.request.get(url + '/projects/dls3d-baseline.mp4', { headers: { Range: 'bytes=0-99' } })
  assert.equal(rangeResponse.status(), 206, 'Video seeking supports byte ranges')
  assert.equal((await rangeResponse.body()).length, 100)
  await page.getByRole('button', { name: 'Play comparison' }).click()
  await page.waitForFunction(() => [...document.querySelectorAll('video')].every(v => !v.paused && v.currentTime > .1))
  const durations = await page.locator('video').evaluateAll(videos => videos.map(v => ({ duration: v.duration, rate: v.playbackRate })))
  assert(Math.abs(durations[0].duration - 11.07) < .1)
  assert(Math.abs(durations[1].duration - 8.74) < .1)
  assert(durations.every(v => v.rate === 1), 'No retiming to stretch the shorter recording')
  await page.waitForFunction(() => { const [base, ours] = document.querySelectorAll('video'); return ours.ended && !base.ended && !base.paused }, { }, { timeout: 20000 })
  await page.locator('.video-hold').waitFor()
  await page.getByRole('button', { name: 'Pause comparison' }).click()
  const pausedAt = await page.locator('video').evaluateAll(videos => videos.map(v => v.currentTime))
  await page.waitForTimeout(300)
  assert.deepEqual(await page.locator('video').evaluateAll(videos => videos.map(v => v.currentTime)), pausedAt, 'Pause holds both recordings')
  await page.screenshot({ path: 'artifacts/projects-video-hold.png', fullPage: true })
  await page.getByRole('button', { name: 'Play comparison' }).click()
  await page.waitForFunction(() => [...document.querySelectorAll('video')].every(v => !v.paused && v.currentTime > .1 && v.currentTime < 2), {}, { timeout: 8000 })
  const replayTimes = await page.locator('video').evaluateAll(videos => videos.map(v => v.currentTime))
  assert(Math.abs(replayTimes[0] - replayTimes[1]) < .25, 'Both restart together after the baseline ends')
  await page.getByRole('button', { name: 'Restart', exact: true }).click()
  await page.waitForFunction(() => [...document.querySelectorAll('video')].every(v => !v.paused && v.currentTime > .1 && v.currentTime < 1))
  await page.getByRole('button', { name: 'Pause comparison' }).click()

  await page.goto(url)
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark', 'First visit defaults to dark')
  assert.equal(await page.locator('.page-index .index-row').count(), 3)
  assert.deepEqual(await page.locator('.nav-number').allTextContents(), ['01', '02', '03', '04'])
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('link', { name: 'Download Resume' }).click()
  assert.equal((await downloadEvent).suggestedFilename(), 'Haris_Amir_resume_vi.pdf')
  assert.equal(await page.locator('.skills-track').evaluate(el => getComputedStyle(el).animationName), 'none', 'Skills stay still with reduced motion')
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.locator('.skills-window').hover()
  assert.equal(await page.locator('.skills-track').evaluate(el => getComputedStyle(el).animationPlayState), 'running', 'Skills continue scrolling on hover')
  assert.equal(await page.locator('.skills-strip button').count(), 0, 'Skills strip has no pause button')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  assert.equal(await page.locator('#experience, #background, .project-row, .publication-row').count(), 0, 'About contains no detailed sections')
  assert.equal(await page.locator('.site-header button').count(), 0, 'No theme toggle')
  await page.evaluate(() => localStorage.setItem('haris-theme', 'light'))
  await page.emulateMedia({ colorScheme: 'light' })
  await page.reload()
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark', 'Legacy light preference cannot change the fixed dark theme')
  assert.equal(await page.locator('html').evaluate(el => getComputedStyle(el).colorScheme), 'dark')
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.locator('.page-index a[href="/projects/"]').click()
  await page.waitForURL('**/projects/')
  assert.equal(await page.title(), 'Projects — Haris Amir')
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Publications' }).click()
  await page.waitForURL('**/publications/')
  assert.equal(await page.title(), 'Publications — Haris Amir')
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Contact' }).click()
  await page.waitForURL('**/contact/')
  await page.locator('.contact-directory').waitFor()
  for (const href of ['mailto:harisamir4@gmail.com', 'https://www.linkedin.com/in/its-haris-amir/', 'https://github.com/HarisAmir', 'https://scholar.google.com/citations?user=j-ZjEP8AAAAJ&hl=en']) {
    assert.equal(await page.locator('.contact-directory a').evaluateAll((links, href) => links.filter(a => a.getAttribute('href') === href).length, href), 1)
  }
  await page.screenshot({ path: 'artifacts/contact-mobile.png', fullPage: true })

  await page.goto(url + '/publications/')
  assert.equal(await page.locator('.publication-card').count(), 1)
  assert.equal(await page.locator('.publication-authors strong').textContent(), 'Muhammad Haris Bin Amir')
  assert.equal(await page.locator('.publication-resources > a').count(), 6)
  const citation = page.locator('.publication-citation')
  await citation.locator('summary').click()
  assert.notEqual(await citation.getAttribute('open'), null, 'BibTeX expands')
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.getByRole('button', { name: 'Copy citation' }).click()
  await page.getByRole('status').filter({ hasText: 'Citation copied.' }).waitFor()
  const copied = await page.evaluate(() => navigator.clipboard.readText())
  assert(copied.includes('@InProceedings{Khan_2026_CVPR,'))
  assert(copied.includes('7893-7902'))
  assert(!(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)), 'Expanded citation fits mobile')
  await citation.locator('summary').click()
  assert.equal(await citation.getAttribute('open'), null, 'BibTeX collapses')

  await page.goto(url)
  await page.keyboard.press('Tab')
  assert.equal(await page.evaluate(() => document.activeElement?.textContent), 'Skip to content')
  await page.keyboard.press('Enter')
  assert.equal(await page.evaluate(() => document.activeElement?.id), 'main')
  assert.equal(await page.locator('.hero-name').evaluate(el => getComputedStyle(el).animationName), 'none', 'Reduced motion respected')
  // Prerendered copy remains readable when JavaScript is disabled.
  const noJs = await browser.newContext({ javaScriptEnabled: false })
  const staticPage = await noJs.newPage()
  await staticPage.goto(url)
  assert((await staticPage.locator('h1').textContent()).includes('Haris Amir'))
  assert.equal(await staticPage.locator('html').getAttribute('data-theme'), 'dark', 'Dark without JavaScript')
  for (const entry of pages) {
    const html = await readFile(`dist${entry.path}index.html`, 'utf8')
    assert(html.includes(`<title>${entry.title} — Haris Amir</title>`), `${entry.path}: prerendered metadata`)
  }
  const sitemap = await readFile('dist/sitemap.xml', 'utf8')
  assert.equal((sitemap.match(/<url>/g) || []).length, 4, 'Exactly four public content pages')
  assert.deepEqual(errors, [], 'No browser or hydration errors on valid routes')
  const missing = await page.goto(url + '/does-not-exist')
  assert.equal(missing.status(), 404)
  assert.equal(await page.locator('h1').textContent(), 'A small detour.')
  await page.getByRole('link', { name: 'Back to home' }).click()
  await page.waitForURL(url + '/')
  console.log(`PASS: ${paths.length} routes × 4 widths; ${links.size} links; project galleries; original-speed video playback, final-frame hold, shared repeat, pause/restart; approved PDFs only; image loading; permanent dark theme; route navigation; keyboard skip link; reduced motion; prerendering; 404 recovery.`)
} finally {
  await browser?.close()
  await new Promise(resolve => server.close(resolve))
}
